// Band split agreements: who gets what share of the band's music income.

export interface Member {
  id: string;
  name: string;
  role: string;
  share: number; // percent, 0..100
  isYou?: boolean;
  musicianId?: string;
  joinedAt: number;
}

export interface SplitCheck {
  total: number;
  valid: boolean;
  message: string;
}

export function checkSplits(members: Member[]): SplitCheck {
  const total = Math.round(members.reduce((a, m) => a + m.share, 0) * 100) / 100;
  if (members.some((m) => m.share < 0)) return { total, valid: false, message: 'Shares cannot be negative.' };
  if (total === 100) return { total, valid: true, message: 'Shares add up to 100%.' };
  const diff = Math.round((100 - total) * 100) / 100;
  return {
    total,
    valid: false,
    message: diff > 0 ? `${diff}% is still unassigned.` : `Shares are over by ${-diff}%.`,
  };
}

/** Split 100% evenly; any rounding remainder goes to the first member */
export function evenSplit(members: Member[]): Member[] {
  if (members.length === 0) return members;
  const base = Math.floor((100 / members.length) * 100) / 100;
  const remainder = Math.round((100 - base * members.length) * 100) / 100;
  return members.map((m, i) => ({ ...m, share: i === 0 ? Math.round((base + remainder) * 100) / 100 : base }));
}

/**
 * Add a new member who was promised `offered`% in their role post. The
 * existing members give up that share in proportion to what they hold.
 */
export function addMemberWithShare(members: Member[], newcomer: Omit<Member, 'share'>, offered: number): Member[] {
  const share = Math.max(0, Math.min(100, offered));
  const existingTotal = members.reduce((a, m) => a + m.share, 0) || 1;
  const scaled = members.map((m) => ({ ...m, share: Math.round(((m.share / existingTotal) * (100 - share)) * 100) / 100 }));
  const all = [...scaled, { ...newcomer, share }];
  // fix rounding drift on the first member so the total is exactly 100
  const drift = Math.round((100 - all.reduce((a, m) => a + m.share, 0)) * 100) / 100;
  if (drift !== 0 && all.length) all[0] = { ...all[0], share: Math.round((all[0].share + drift) * 100) / 100 };
  return all;
}

export function splitSheet(bandName: string, members: Member[], date = new Date()): string {
  const check = checkSplits(members);
  const lines = [
    `${bandName} — Split agreement`,
    `Generated by ENCORE OS on ${date.toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}`,
    '',
    ...members.map((m) => `${m.name.padEnd(22)} ${m.role.padEnd(18)} ${m.share.toFixed(2).padStart(6)}%`),
    '',
    `Total: ${check.total.toFixed(2)}%`,
    'Applies to: streaming royalties, live show fees and sync income from songs released as this band.',
    'This is a prototype summary, not a legal contract.',
  ];
  return lines.join('\n');
}
